#!/home/jfernandes/.venv/bin/python
"""Push, submit, monitor, pull back, and clean up M3D-C1 scenario-tree cases
on a remote SLURM cluster over SSH.

Operates on a scenario tree generated by generate_scenario.py (see that file
and ../CLAUDE.md for the tree layout and scenario.json schema). Requires a
"cluster" block in scenario.json (host/remote_base_dir/user) that
generate_scenario.py itself does not need or validate. State (linked-status,
SLURM job ID, last-known job state per case) is cached in
<scenario-root>/.remote_state.json between invocations.

Every ssh/rsync round trip is deliberately batched across all selected cases
(one ssh call for push's make_links step, one each for submit/status/clean)
since key-based ssh handshake overhead is non-negligible across the ~48 cases
in a full scenario tree. pull is the one exception: rsync's include/exclude
glob engine can't cheaply be scoped to an arbitrary subset of case
directories in a single call, so pull runs one rsync per eligible case.

Batching is purely a connection-count optimization for whatever subset
--cases selects -- it does not require operating on all cases at once; a
single case is just a batch of size one.
"""
import argparse
import fnmatch
import json
import re
import shlex
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

import generate_scenario as gs

STATE_FILE_NAME = ".remote_state.json"

REQUIRED_CLUSTER_KEYS = ["host", "remote_base_dir", "user"]

# Mirrors generate_scenario.RMALL_CONTENT's cleanup targets ("rm -rf C1ke
# normcurv *out profiles* *.h5") plus C1stdout, which the batch script writes
# but rmall doesn't clean up. Kept as a separate literal rather than parsed
# out of RMALL_CONTENT's free-text rm line -- not worth the fragility for one
# small static list.
OUTPUT_ARTIFACT_GLOBS = ["C1stdout", "*.h5", "C1ke", "normcurv", "*out", "profiles*"]

NONTERMINAL_SLURM_STATES = {
    "PENDING", "RUNNING", "CONFIGURING", "COMPLETING", "SUSPENDED", "SUBMITTED",
}
TERMINAL_FAILURE_STATES = {
    "FAILED", "CANCELLED", "TIMEOUT", "OUT_OF_MEMORY", "NODE_FAIL", "BOOT_FAIL", "DEADLINE",
}

SUBMIT_MARKER_RE = re.compile(r"^SUBMIT (\S+)$")
SBATCH_JOBID_RE = re.compile(r"^Submitted batch job (\d+)$")
# Shared shape for push's "LINKRESULT <relpath> <exit_code>" and clean's
# "CLEANRESULT <relpath> <exit_code>" marker lines -- see parse_result_lines.
RESULT_MARKER_RE = re.compile(r"^(\S+) (\S+) (\d+)$")


# ---------------------------------------------------------------------------
# config / state
# ---------------------------------------------------------------------------

def load_cluster_config(root):
    """Load scenario.json's "cluster" block.

    Parameters
    ----------
    root : Path
        Root directory of the scenario tree (contains scenario.json).

    Returns
    -------
    dict
        The "cluster" sub-dict with keys host/remote_base_dir/user.
    """
    config = gs.load_config(root / "scenario.json")
    cluster = config.get("cluster")
    if cluster is None:
        raise SystemExit(
            f"{root / 'scenario.json'} has no 'cluster' block -- required by remote_run.py "
            "(host/remote_base_dir/user), see template/CLAUDE.md"
        )
    missing = [k for k in REQUIRED_CLUSTER_KEYS if k not in cluster]
    if missing:
        raise SystemExit(f"scenario.json 'cluster' block missing key(s): {', '.join(missing)}")
    return cluster


def remote_target(cluster):
    return f"{cluster['host']}:{cluster['remote_base_dir']}"


def load_state(root):
    """Load <root>/.remote_state.json, or an empty state if absent.

    Parameters
    ----------
    root : Path
        Root directory of the scenario tree.

    Returns
    -------
    dict
        {"remote_target": str or None, "cases": {relpath: {...}}}
    """
    path = root / STATE_FILE_NAME
    if not path.exists():
        return {"remote_target": None, "cases": {}}
    return json.loads(path.read_text())


def save_state(root, state):
    """Write state back to <root>/.remote_state.json."""
    (root / STATE_FILE_NAME).write_text(json.dumps(state, indent=2, sort_keys=True) + "\n")


def check_remote_target(state, cluster):
    """Guard against reusing cached job IDs/linked-flags against a different
    remote host/directory than the one they were recorded against. Updates
    state in place with the current target on first use."""
    current = remote_target(cluster)
    recorded = state.get("remote_target")
    if recorded is not None and recorded != current:
        raise SystemExit(
            f"scenario.json's cluster target ({current}) does not match the target recorded in "
            f"{STATE_FILE_NAME} ({recorded}). Cached job IDs/linked-flags may refer to a "
            "different remote location -- resolve manually before continuing "
            "(e.g. delete .remote_state.json if this is intentional)."
        )
    state["remote_target"] = current


def utc_now_iso():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def parse_job_name(case_dir):
    """Read the #SBATCH -J line out of a case's own batch_script.response,
    rather than recomputing it from FLUID_PARAMS, so it can never drift from
    what was actually submitted."""
    batch = (case_dir / "batch_script.response").read_text()
    m = gs.JOB_NAME_LINE_RE.search(batch)
    if not m:
        raise SystemExit(f"{case_dir / 'batch_script.response'}: could not find #SBATCH -J line")
    return m.group(1)


# ---------------------------------------------------------------------------
# case selection
# ---------------------------------------------------------------------------

def select_cases(root, cases_arg):
    """Discover case directories and filter them by the --cases selector.

    Parameters
    ----------
    root : Path
        Root directory of the scenario tree.
    cases_arg : str or None
        Comma-separated fnmatch glob patterns matched against case relpaths
        (e.g. "n1/*/coil_sets_1kAt/CPL_set_000"). None selects every case.

    Returns
    -------
    list of (Path, str)
        (case_dir, relpath) pairs, sorted by relpath.
    """
    cases, malformed = gs.discover_cases(root)
    if malformed:
        print(f"warning: {len(malformed)} malformed case-like director"
              f"{'y' if len(malformed) == 1 else 'ies'} ignored "
              "(run generate_scenario.py validate for details)", file=sys.stderr)
    all_cases = [(path, rel) for path, rel, _m in cases]

    if cases_arg is None:
        selected = all_cases
    else:
        patterns = [p.strip() for p in cases_arg.split(",") if p.strip()]
        selected = [(path, rel) for path, rel in all_cases
                    if any(fnmatch.fnmatch(rel, pat) for pat in patterns)]

    if not selected:
        raise SystemExit(f"--cases {cases_arg!r} matched no case directories under {root}")
    return selected


# ---------------------------------------------------------------------------
# ssh / rsync primitives
# ---------------------------------------------------------------------------

def ssh_run(cluster, script_text):
    """Run a bash script on the remote host over ssh, piped via stdin.

    stderr is not captured -- it streams straight to the user's terminal, so
    remote command failures surface with their original messages intact.

    Parameters
    ----------
    cluster : dict
        Cluster config (needs "host").
    script_text : str
        Bash script body, executed as `ssh <host> bash -s`.

    Returns
    -------
    str
        The remote command's stdout.
    """
    result = subprocess.run(
        ["ssh", cluster["host"], "bash", "-s"],
        input=script_text, text=True, stdout=subprocess.PIPE, check=True,
    )
    return result.stdout


def rsync_push(cluster, root, cases):
    """rsync the known input files for `cases` from local to remote.

    Only files that exist locally and are named in generate_scenario.CASE_FILES
    are transferred; never touches remote-side solver output (not in that
    set). --checksum (not mtime/size) because generate_scenario.py init
    --force rewrites file bytes on every re-render even when content is
    unchanged for a given axis combination.

    Parameters
    ----------
    cluster : dict
    root : Path
    cases : list of (Path, str)
        (case_dir, relpath) pairs to push.
    """
    filelist_lines = [
        f"{rel}/{name}"
        for path, rel in cases
        for name in gs.CASE_FILES
        if (path / name).exists()
    ]
    if not filelist_lines:
        print("push: nothing to transfer (no known input files found locally)")
        return

    dest = f"{cluster['host']}:{cluster['remote_base_dir']}/"
    subprocess.run(
        ["rsync", "-a", "--checksum", "--files-from=-", "--relative", f"{root}/", dest],
        input="\n".join(filelist_lines) + "\n", text=True, check=True,
    )


def rsync_pull_case(cluster, root, relpath):
    """rsync the known output artifacts for one case from remote to local.
    No --delete: pulling must never remove a local file just because it's
    absent remotely."""
    src = f"{cluster['host']}:{cluster['remote_base_dir']}/{relpath}/"
    args = ["rsync", "-a"]
    for pattern in OUTPUT_ARTIFACT_GLOBS:
        args.append(f"--include={pattern}")
    args += ["--exclude=*", src, f"{root / relpath}/"]
    subprocess.run(args, check=True)


def build_link_script(cluster, relpaths_to_link):
    """Bash script for push's ssh round trip: ensure remote_base_dir exists,
    then run ./make_links for each relpath, reporting per-case exit codes so
    Python can attribute results back to individual local state entries.
    Deliberately not wrapped in `set -e` -- one case's failure must not abort
    the rest of the batch."""
    lines = [f"mkdir -p {shlex.quote(cluster['remote_base_dir'])}"]
    for rel in relpaths_to_link:
        remote_dir = f"{cluster['remote_base_dir']}/{rel}"
        lines.append(
            f'(cd {shlex.quote(remote_dir)} && ./make_links); echo "LINKRESULT {rel} $?"'
        )
    return "\n".join(lines) + "\n"


def parse_result_lines(stdout, marker):
    """Parse '<marker> <relpath> <exit_code>' lines into {relpath: code}.
    Shared by push's LINKRESULT and clean's CLEANRESULT markers."""
    results = {}
    for line in stdout.splitlines():
        m = RESULT_MARKER_RE.match(line)
        if m and m.group(1) == marker:
            results[m.group(2)] = int(m.group(3))
    return results


def build_submit_script(cluster, relpaths):
    """Bash script for submit's ssh round trip: sbatch each case, each
    preceded by a 'SUBMIT <relpath>' marker line so Python can pair sbatch's
    own 'Submitted batch job <id>' output back to the right case."""
    lines = []
    for rel in relpaths:
        remote_dir = f"{cluster['remote_base_dir']}/{rel}"
        lines.append(f'echo "SUBMIT {rel}"')
        lines.append(f"(cd {shlex.quote(remote_dir)} && sbatch batch_script.response)")
    return "\n".join(lines) + "\n"


def parse_sbatch_output(stdout):
    """Parse combined 'SUBMIT <relpath>' / 'Submitted batch job <id>' pairs.

    Returns
    -------
    dict
        relpath -> job_id (str), only for cases where a job ID was found.
    """
    job_ids = {}
    current = None
    for line in stdout.splitlines():
        m = SUBMIT_MARKER_RE.match(line)
        if m:
            current = m.group(1)
            continue
        m = SBATCH_JOBID_RE.match(line)
        if m and current is not None:
            job_ids[current] = m.group(1)
            current = None
    return job_ids


def build_status_script(job_ids):
    """sacct is the primary source (squeue drops jobs the instant they leave
    the queue, so it can't distinguish completed/failed/never-existed);
    squeue is queried in the same round trip as a fallback for jobs sacct
    hasn't caught up on yet right after submission."""
    ids_csv = ",".join(job_ids)
    return (
        f"sacct -j {ids_csv} --format=JobID,State --parsable2 --noheader\n"
        "echo '---SQUEUE---'\n"
        f"squeue -j {ids_csv} --format='%i|%T' --noheader\n"
    )


def build_clean_script(cluster, relpaths):
    """Bash script for clean's ssh round trip: run each case's own ./rmall
    (the existing per-case output-cleanup script) rather than reimplementing
    file removal here, so clean can never drift from what a manual single-case
    cleanup already does. Reports per-case exit codes like build_link_script.
    Not wrapped in `set -e` -- one case's failure must not abort the batch."""
    lines = []
    for rel in relpaths:
        remote_dir = f"{cluster['remote_base_dir']}/{rel}"
        lines.append(
            f'(cd {shlex.quote(remote_dir)} && ./rmall); echo "CLEANRESULT {rel} $?"'
        )
    return "\n".join(lines) + "\n"


def parse_status_output(stdout, job_ids):
    """Parse combined sacct + squeue output into {job_id: state}, preferring
    sacct's bare JobID row (skipping .batch/.extern sub-steps) and falling
    back to squeue for any job ID sacct didn't report."""
    sacct_part, _, squeue_part = stdout.partition("---SQUEUE---")
    states = {}
    for line in sacct_part.splitlines():
        line = line.strip()
        if not line or "|" not in line:
            continue
        jid, jstate = line.split("|", 1)
        if "." in jid:
            continue
        states[jid] = jstate.split()[0] if jstate.strip() else "UNKNOWN"

    for line in squeue_part.splitlines():
        line = line.strip()
        if not line or "|" not in line:
            continue
        jid, jstate = line.split("|", 1)
        states.setdefault(jid, jstate)

    return {jid: states.get(jid, "UNKNOWN") for jid in job_ids}


