def cmd_push(args):
    root = Path(args.path).resolve()
    cluster = load_cluster_config(root)
    state = load_state(root)
    check_remote_target(state, cluster)
    cases = select_cases(root, args.cases)

    to_link = [rel for _path, rel in cases
               if args.force_relink or not state["cases"].get(rel, {}).get("linked", False)]
    link_script = build_link_script(cluster, to_link)

    if args.dry_run:
        filelist = [f"{rel}/{name}" for path, rel in cases
                    for name in gs.CASE_FILES if (path / name).exists()]
        print("--- rsync file list ---")
        print("\n".join(filelist))
        print("--- ssh (make_links) ---")
        print(link_script, end="")
        return

    # rsync first: make_links needs the case directory (and the make_links
    # script itself) to already exist remotely, which on a fresh
    # remote_base_dir is only true after this transfer -- --relative makes
    # rsync create the full directory tree, so no separate mkdir is needed.
    rsync_push(cluster, root, cases)

    stdout = ssh_run(cluster, link_script)
    print(stdout, end="")
    results = parse_result_lines(stdout, "LINKRESULT")
    for rel, code in results.items():
        state["cases"].setdefault(rel, {})
        if code == 0:
            state["cases"][rel]["linked"] = True
        else:
            print(f"warning: make_links failed for {rel} (exit {code}), left unlinked", file=sys.stderr)

    save_state(root, state)
    print(f"push: transferred input files for {len(cases)} case(s)")


def cmd_submit(args):
    root = Path(args.path).resolve()
    cluster = load_cluster_config(root)
    state = load_state(root)
    check_remote_target(state, cluster)
    cases = select_cases(root, args.cases)

    eligible = []
    for path, rel in cases:
        case_state = state["cases"].get(rel, {})
        last_state = case_state.get("last_state")
        if last_state in NONTERMINAL_SLURM_STATES and not args.force:
            print(f"skip {rel}: already has active job {case_state.get('job_id')} "
                  f"(state={last_state}), use --force to resubmit")
            continue
        eligible.append((path, rel))

    if not eligible:
        print("submit: nothing to submit")
        return

    script = build_submit_script(cluster, [rel for _p, rel in eligible])

    if args.dry_run:
        print("--- ssh (sbatch) ---")
        print(script, end="")
        return

    stdout = ssh_run(cluster, script)
    print(stdout, end="")
    job_ids = parse_sbatch_output(stdout)

    now = utc_now_iso()
    for path, rel in eligible:
        job_id = job_ids.get(rel)
        if job_id is None:
            print(f"warning: no job ID parsed for {rel}, sbatch may have failed", file=sys.stderr)
            continue
        state["cases"].setdefault(rel, {})
        state["cases"][rel].update({
            "job_id": job_id,
            "job_name": parse_job_name(path),
            "submitted_at": now,
            "last_state": "SUBMITTED",
        })

    save_state(root, state)
    print(f"submit: {len(job_ids)}/{len(eligible)} case(s) submitted")


def cmd_status(args):
    root = Path(args.path).resolve()
    cluster = load_cluster_config(root)
    state = load_state(root)
    check_remote_target(state, cluster)
    cases = select_cases(root, args.cases)

    with_job = [(rel, state["cases"][rel]["job_id"]) for _p, rel in cases
                if state["cases"].get(rel, {}).get("job_id")]
    n_no_job = len(cases) - len(with_job)

    if with_job:
        job_ids = [jid for _rel, jid in with_job]
        stdout = ssh_run(cluster, build_status_script(job_ids))
        job_states = parse_status_output(stdout, job_ids)
        now = utc_now_iso()
        for rel, jid in with_job:
            state["cases"][rel]["last_state"] = job_states[jid]
            state["cases"][rel]["last_checked_at"] = now

    save_state(root, state)

    n_completed = n_failed = n_flight = 0
    for _path, rel in cases:
        case_state = state["cases"].get(rel, {})
        jid = case_state.get("job_id")
        if jid is None:
            print(f"{rel}: no job submitted")
            continue
        st = case_state.get("last_state", "UNKNOWN")
        print(f"{rel}: job={jid} state={st}")
        if st == "COMPLETED":
            n_completed += 1
        elif st in TERMINAL_FAILURE_STATES:
            n_failed += 1
        else:
            n_flight += 1

    print(f"\n{n_completed} completed, {n_failed} failed, {n_flight} in flight, "
          f"{n_no_job} not submitted")


def cmd_pull(args):
    root = Path(args.path).resolve()
    cluster = load_cluster_config(root)
    state = load_state(root)
    check_remote_target(state, cluster)
    cases = select_cases(root, args.cases)

    eligible = []
    for _path, rel in cases:
        case_state = state["cases"].get(rel, {})
        job_id = case_state.get("job_id")
        if job_id is None:
            print(f"skip {rel}: no job submitted")
            continue
        last_state = case_state.get("last_state")
        if last_state != "COMPLETED" and not args.all:
            print(f"skip {rel}: state={last_state} (use --all to pull anyway)")
            continue
        eligible.append(rel)

    if not eligible:
        print("pull: nothing to pull")
        return

    if args.dry_run:
        for rel in eligible:
            print(f"rsync {remote_target(cluster)}/{rel}/ -> {root / rel}/  "
                  f"(globs: {', '.join(OUTPUT_ARTIFACT_GLOBS)})")
        return

    now = utc_now_iso()
    for rel in eligible:
        rsync_pull_case(cluster, root, rel)
        state["cases"][rel]["pulled_at"] = now
        print(f"pulled {rel}")

    save_state(root, state)


def cmd_clean(args):
    root = Path(args.path).resolve()
    cluster = load_cluster_config(root)
    state = load_state(root)
    check_remote_target(state, cluster)
    cases = select_cases(root, args.cases)

    eligible = []
    for _path, rel in cases:
        case_state = state["cases"].get(rel, {})
        job_id = case_state.get("job_id")
        if job_id is None:
            print(f"skip {rel}: no job submitted, nothing to clean")
            continue
        last_state = case_state.get("last_state")
        if last_state in NONTERMINAL_SLURM_STATES:
            # Never overridable by --force: rmall would delete output files a
            # running/pending job is actively writing.
            print(f"skip {rel}: job is still {last_state}, refusing to clean a live run's output")
            continue
        if last_state != "COMPLETED" or not case_state.get("pulled_at"):
            if not args.force:
                print(f"skip {rel}: state={last_state}, pulled="
                      f"{'yes' if case_state.get('pulled_at') else 'no'} (use --force to clean anyway)")
                continue
        eligible.append(rel)

    if not eligible:
        print("clean: nothing to clean")
        return

    script = build_clean_script(cluster, eligible)

    if args.dry_run:
        print("--- ssh (rmall) ---")
        print(script, end="")
        return

    stdout = ssh_run(cluster, script)
    print(stdout, end="")
    results = parse_result_lines(stdout, "CLEANRESULT")
    now = utc_now_iso()
    for rel, code in results.items():
        if code == 0:
            state["cases"][rel]["cleaned_at"] = now
        else:
            print(f"warning: rmall failed for {rel} (exit {code})", file=sys.stderr)

    save_state(root, state)
    print(f"clean: cleaned {len(results)}/{len(eligible)} case(s)")


# ---------------------------------------------------------------------------

def add_common_args(p):
    p.add_argument("--path", default=".", help="root directory of the scenario tree (default: .)")
    p.add_argument("--cases", default=None,
                    help="comma-separated fnmatch glob(s) against case relpaths "
                         "(e.g. 'n1/*/coil_sets_1kAt/CPL_set_000'); default: all cases")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    p_push = sub.add_parser("push", help="push case input files and run make_links on the cluster")
    add_common_args(p_push)
    p_push.add_argument("--force-relink", action="store_true", help="re-run make_links even if already linked")
    p_push.add_argument("--dry-run", action="store_true", help="print planned ssh/rsync commands without running them")
    p_push.set_defaults(func=cmd_push)

    p_submit = sub.add_parser("submit", help="submit case batch_script.response via sbatch")
    add_common_args(p_submit)
    p_submit.add_argument("--force", action="store_true", help="resubmit even if a non-terminal job is already tracked")
    p_submit.add_argument("--dry-run", action="store_true", help="print the planned sbatch script without running it")
    p_submit.set_defaults(func=cmd_submit)

    p_status = sub.add_parser("status", help="check SLURM job status for tracked cases")
    add_common_args(p_status)
    p_status.set_defaults(func=cmd_status)

    p_pull = sub.add_parser("pull", help="pull back solver output artifacts for completed cases")
    add_common_args(p_pull)
    p_pull.add_argument("--all", action="store_true", help="pull regardless of tracked job state (default: only COMPLETED)")
    p_pull.add_argument("--dry-run", action="store_true", help="print planned rsync commands without running them")
    p_pull.set_defaults(func=cmd_pull)

    p_clean = sub.add_parser("clean", help="run ./rmall remotely to remove solver output for already-pulled cases")
    add_common_args(p_clean)
    p_clean.add_argument("--force", action="store_true",
                          help="clean even if not confirmed COMPLETED+pulled "
                               "(never overrides the running-job guard)")
    p_clean.add_argument("--dry-run", action="store_true", help="print the planned rmall script without running it")
    p_clean.set_defaults(func=cmd_clean)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
